run("current=createEntry(parseRoute('words/19968/1'))");
const related=run('workingView().content');assert.match(related,/13 слов/);assert.doesNotMatch(related,/13 из 13|13 of 13/);
run("current=createEntry(parseRoute('kanji/26085/2'))");
assert.match(run('workingKanjiDetails()'),/чтения китайского происхождения/);
assert.match(run('workingKanjiDetails()'),/Японская школа/);
assert.match(run('workingKanjiDetails()'),/общеупотребительные/);
