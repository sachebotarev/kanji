assert.equal(run('chaptersFor(1,sourceSelection())[0].kanjiCount'),1);
assert.equal(run('chaptersFor(1,sourceSelection())[0].wordCount'),118);
run("current.route={kind:'filter',filter:'chapter',sourceId:1,forWords:false,selected:0};current.query=''");
assert.doesNotMatch(run('workingChapterCard(chaptersFor(1)[0],true)'),/118 слов/);
