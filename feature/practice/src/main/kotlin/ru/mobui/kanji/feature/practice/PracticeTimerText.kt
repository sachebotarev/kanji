internal fun formatTime(ms: Long): String = formatTimerSeconds(ms / MILLIS_PER_SECOND)

internal fun formatTimerSeconds(seconds: Long): String {
    val minutes = seconds / SECONDS_PER_MINUTE
    return if (minutes < SECONDS_PER_MINUTE)
        "%02d:%02d".format(minutes, seconds % SECONDS_PER_MINUTE)
    else
        "%d:%02d:%02d"
            .format(
                minutes / SECONDS_PER_MINUTE,
                minutes % SECONDS_PER_MINUTE,
                seconds % SECONDS_PER_MINUTE,
            )
}


private const val MILLIS_PER_SECOND = 1000

private const val SECONDS_PER_MINUTE = 60
